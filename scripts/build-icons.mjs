// Copies the few Lucide icons the arcade uses into js/core/icons.js,
// so the page doesn't ship the whole 350 KB icon library.
import { writeFileSync } from 'node:fs';

const ICONS = ['gamepad-2', 'flask-conical', 'trees', 'bug', 'atom', 'volume-2', 'volume-x', 'book', 'undo-2', 'cpu', 'users', 'trophy', 'lightbulb', 'gauge'];

const toAttrs = (attrs) => Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(' ');

const out = {};
for (const name of ICONS) {
    const mod = await import(`../node_modules/lucide/dist/esm/icons/${name}.js`);
    const [, , children] = mod.default;
    out[name] = children.map(([tag, attrs]) => `<${tag} ${toAttrs(attrs)}/>`).join('');
}

const body = `// Generated by scripts/build-icons.mjs from lucide@0.460.0 (ISC licence). Do not edit by hand.

export const ICONS = ${JSON.stringify(out, null, 4)};
`;
writeFileSync(new URL('../js/core/icons.js', import.meta.url), body);
console.log(`Wrote ${ICONS.length} icons`);
